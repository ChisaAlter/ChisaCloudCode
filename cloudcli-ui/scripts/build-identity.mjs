import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

// Build-time only: runtime version reads never launch Git or other tools.
export function captureBuildIdentity() {
  const root = fileURLToPath(new URL('../', import.meta.url));
  const version = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8')).version;
  let commit = null;
  let dirty = null;
  try {
    commit = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: root, encoding: 'utf8', windowsHide: true }).trim();
    dirty = execFileSync('git', ['status', '--porcelain', '--untracked-files=normal', '--', ':/', ':(top,exclude)cloudcli-ui/shared/build-identity.json'], { cwd: root, encoding: 'utf8', windowsHide: true }).trim().length > 0;
  } catch { /* Source archives have no verifiable Git identity. */ }
  return { version, commit, dirty, builtAt: new Date().toISOString() };
}

if (process.argv.includes('--server')) {
  writeFileSync(new URL('../shared/build-identity.json', import.meta.url), JSON.stringify(captureBuildIdentity()));
}

if (process.argv.includes('--native')) {
  const identity = captureBuildIdentity();
  const config = readFileSync(new URL('../../app/mygo.config.ts', import.meta.url), 'utf8');
  identity.version = config.match(/\bversion:\s*"([^"]+)"/)?.[1] ?? null;
  writeFileSync(new URL('../../app/build_identity_generated.go', import.meta.url),
    `// Code generated by build-identity.mjs. DO NOT EDIT.\npackage main\nfunc init() { nativeBuildIdentityJSON = ${JSON.stringify(JSON.stringify(identity))} }\n`);
}
